"""Convert geoBoundaries LKA ADM1 (provinces) GeoJSON into compact SVG paths for the dashboard map.
Source: geoBoundaries gbOpen LKA ADM1 (simplified), CC BY 4.0, https://www.geoboundaries.org
Usage: python3 scripts/build_map.py /tmp/lka_raw.geojson
"""
import json, math, sys
src = json.load(open(sys.argv[1]))
S, PAD = 150.0, 10  # px per degree
pts = [c for f in src["features"] for poly in (f["geometry"]["coordinates"] if f["geometry"]["type"] == "MultiPolygon" else [f["geometry"]["coordinates"]]) for ring in poly for c in ring]
lon0, lon1 = min(p[0] for p in pts), max(p[0] for p in pts)
lat0, lat1 = min(p[1] for p in pts), max(p[1] for p in pts)
k = math.cos(math.radians((lat0 + lat1) / 2))
X = lambda lon: round((lon - lon0) * k * S + PAD, 1)
Y = lambda lat: round((lat1 - lat) * S + PAD, 1)
out = []
for f in src["features"]:
    g = f["geometry"]; polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
    d, cx, cy, n = "", 0, 0, 0
    for poly in polys:
        for ring in poly:
            d += "M" + "L".join(f"{X(a)},{Y(b)}" for a, b in ring) + "Z"
            for a, b in ring: cx += X(a); cy += Y(b); n += 1
    name = f["properties"]["shapeName"].replace(" Province", "")
    out.append(dict(name=name, d=d, cx=round(cx / n, 1), cy=round(cy / n, 1)))
w, h = round((lon1 - lon0) * k * S + 2 * PAD), round((lat1 - lat0) * S + 2 * PAD)
js = "// Generated by scripts/build_map.py from geoBoundaries (CC BY 4.0).\nexport const MAP_SIZE = { w: %d, h: %d };\nexport const PROVINCES = %s;\n" % (w, h, json.dumps(out))
open("frontend/src/data/provinces.js", "w").write(js); print(w, h, len(js), "bytes")
